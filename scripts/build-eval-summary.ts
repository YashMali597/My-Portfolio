// Folds eval/results.json into src/data/eval-summary.ts for the /system page.
//
// Runs as part of `npm run knowledge:build`. Deliberately tolerant: if the eval
// has never been run, it emits `hasResults: false` rather than failing the
// build, so the site builds on a machine with no API keys and the page shows an
// honest empty state instead of fabricated numbers.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const OUT_PATH = join(ROOT, "src", "data", "eval-summary.ts");

interface Loaded {
  summary: any;
  results: any[];
}

function load(): Loaded | null {
  try {
    return JSON.parse(readFileSync(join(ROOT, "eval", "results.json"), "utf8"));
  } catch {
    return null;
  }
}

const banner = `// AUTO-GENERATED by \`npm run knowledge:build\` from eval/results.json.
// DO NOT EDIT BY HAND — your changes will be overwritten.
//
// Regenerate the underlying numbers with \`npm run eval\` (requires API keys),
// then re-run \`npm run knowledge:build\`. If the eval has never been run,
// hasResults is false and the /system page renders an empty state rather than
// inventing figures.
`;

const types = `
export interface EvalRate {
  passed: number;
  total: number;
  /** null when no item in the set was applicable. */
  rate: number | null;
}

export interface EvalFailure {
  id: string;
  question: string;
  mode: string;
  reason: string;
}

export interface EvalModels {
  router: string;
  routerProvider: string;
  generation: string;
  generationProvider: string;
  judge?: string;
}

export interface EvalSummary {
  hasResults: boolean;
  generatedAt?: string;
  datasetVersion?: number;
  /** Which models actually produced these numbers — recorded so published
   *  figures can never be misattributed to the deployed defaults. */
  models?: EvalModels;
  itemCount?: number;
  datasetSize: number;
  retrieval?: EvalRate;
  sectionPrecision?: EvalRate;
  groundedness?: EvalRate;
  behaviour?: EvalRate;
  byMode?: Record<string, EvalRate>;
  latencyMs?: { mean: number; p50: number; p95: number; max: number };
  tokens?: { input: number; output: number; reported: boolean };
  estimatedCostUsd?: number;
  errors?: number;
  /** Items that failed, so the page can show what broke, not just a score. */
  failures: EvalFailure[];
}
`;

function main() {
  const datasetSize: number = (() => {
    try {
      return JSON.parse(readFileSync(join(ROOT, "eval", "dataset.json"), "utf8")).items.length;
    } catch {
      return 0;
    }
  })();

  const loaded = load();

  let summary: any;
  if (!loaded?.summary) {
    summary = { hasResults: false, datasetSize, failures: [] };
    console.log(`\n  Wrote src/data/eval-summary.ts (no eval results yet — page shows empty state)`);
  } else {
    const failures: any[] = (loaded.results ?? [])
      .filter((r) => r.behaviourPass === false || r.grounded === false || r.retrievalHit === false)
      .map((r) => ({
        id: r.id,
        question: r.question,
        mode: r.mode,
        reason:
          r.retrievalHit === false
            ? `retrieval missed ${r.expectedSource}`
            : r.behaviourPass === false
              ? r.behaviourNote
              : r.judgeReason || "ungrounded claim",
      }));

    summary = { hasResults: true, datasetSize, ...loaded.summary, failures };
    console.log(`\n  Wrote src/data/eval-summary.ts`);
    console.log(`    ${loaded.summary.itemCount} items, ${failures.length} failure(s)`);
  }

  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(
    OUT_PATH,
    `${banner}${types}\nexport const evalSummary: EvalSummary = ${JSON.stringify(summary, null, 2)};\n`,
    "utf8"
  );
}

main();
